import assert from 'node:assert/strict';
import fs from 'node:fs';
import { reviewLetter } from '../assets/cover-letter-checker.mjs';

const letter = `Dear Hiring Manager,\n\nI am applying for the Support Analyst role at Example Company. I am interested in its support work and would welcome a discussion of the team's priorities.\n\nI documented access requests, checked the required approval and referred exceptions to my supervisor. I maintained handover notes so the next shift could continue without repeating the same checks.\n\nThank you for considering my application.\nBest regards,\nFictional Applicant`;
assert.match(reviewLetter().error, /Paste/);
assert.match(reviewLetter({ letter: 42 }).error, /plain text/);
assert.match(reviewLetter({ letter: 'too short' }).error, /30 words/);
assert.match(reviewLetter({ letter: 'a'.repeat(12001) }).error, /12,000/);
assert.match(reviewLetter({ letter, requirements: 'a\nb\nc\nd\ne\nf\ng' }).error, /six/);
assert.match(reviewLetter({ letter, role: 'x'.repeat(161) }).error, /160/);
assert.match(reviewLetter({ letter, requirements: 'x'.repeat(1201) }).error, /1,200/);
const result = reviewLetter({ letter, role: 'Support Analyst', employer: 'Example Company', requirements: 'handover notes\nSQL\nACCESS   REQUESTS' });
assert.equal(result.error, undefined);
assert.deepEqual(result.requirements.map(item => item.found), [true, false, true]);
assert.equal(result.signals.find(item => item.title === 'Target role').detail.startsWith('The text you entered appears'), true);
assert.equal(result.signals.find(item => item.title === 'Employer').detail.startsWith('The text you entered appears'), true);
assert.match(reviewLetter({ letter, role: 'Accountant' }).signals.find(item => item.title === 'Target role').detail, /not found/);
assert.match(reviewLetter({ letter }).signals.find(item => item.title === 'Employer').detail, /Not checked/);
assert.match(reviewLetter({ letter: letter + '\n[Company Name] {{role}}' }).signals.find(item => item.title === 'Unfinished template text').detail, /Possible placeholders/);
assert.match(result.signals.find(item => item.title === 'Unfinished template text').detail, /No supported/);
assert.match(reviewLetter({ letter: letter + ' I am a perfect fit.' }).signals.find(item => item.title === 'Generic wording').detail, /stock phrase/);
assert.equal('score' in result, false);
assert.equal('grade' in result, false);
assert.equal(result.manual.length, 4);
const hostile = '<img src=x onerror=alert(1)>';
assert.equal(reviewLetter({ letter, requirements: hostile }).requirements[0].text, hostile);
assert.equal(reviewLetter({ letter, requirements: '\n\n  \n' }).requirements.length, 0);
assert.ok(reviewLetter({ letter: 'word '.repeat(2400) }).words === 2400);
const script = fs.readFileSync(new URL('../assets/cover-letter-checker.mjs', import.meta.url), 'utf8');
for (const api of ['innerHTML', 'fetch(', 'XMLHttpRequest', 'sendBeacon', 'localStorage', 'sessionStorage', 'document.cookie', 'indexedDB', 'WebSocket']) assert.equal(script.includes(api), false, api);
const page = fs.readFileSync(new URL('../tools/cover-letter-checker/index.html', import.meta.url), 'utf8');
assert.equal((page.match(/src="https?:/g) || []).length, 0);
assert.match(page, /connect-src 'none'/);
assert.match(page, /form-action 'none'/);
assert.equal(/<form\b/i.test(page), false);
assert.match(script, /textContent = text/);
console.log('PASS: local cover-letter rules, input bounds, literal matching, non-HTML output and no network/storage APIs');

export function getPracticePlan(id) {
 const role=ROLES.find(item=>item.id===id);
 if(!role)return null;
 return {id:role.id,name:role.name,guide:role.guide,questions:[...COMMON,...role.questions].map(([question,framework,followup])=>({question,framework,followup}))};
}
if(typeof document!=='undefined'){
 const root=document.querySelector('[data-interview-prep]');
 if(root){
  const select=root.querySelector('#ip-role'),output=root.querySelector('#ip-results'),status=root.querySelector('#ip-status');
  const add=(tag,text,parent=output)=>{const el=document.createElement(tag);el.textContent=text;parent.append(el);return el;};
  const clear=()=>{output.replaceChildren();select.value='';status.textContent='Practice notes cleared from this page. Your browser or device may keep its own history.';};
  const resetOutput=()=>{output.replaceChildren();status.textContent='Role changed. Previous notes cleared. Choose Build my practice plan to start.';};
  select.addEventListener('change',resetOutput);
  root.querySelector('#ip-clear').addEventListener('click',()=>{clear();select.focus();});
  window.addEventListener('pagehide',clear);
  root.querySelector('#ip-build').addEventListener('click',()=>{
   const plan=getPracticePlan(select.value);
   if(!plan){status.textContent='Choose a role family first.';select.focus();return;}
   output.replaceChildren();add('h2',plan.name+' practice plan');
   add('p','Six editorial practice prompts, not a prediction of the questions you will be asked. Notes are not reviewed or scored. Use only real examples and remove confidential details.');
   const link=add('a','Read the '+plan.name.toLowerCase()+' guide');link.href=plan.guide;
   plan.questions.forEach((item,index)=>{
    const section=add('section','');add('h3',(index+1)+'. '+item.question,section);add('p',item.framework,section);add('p','Follow-up to practise: '+item.followup,section);
    const id='ip-note-'+index,label=add('label','Your private practice notes (optional)',section);label.htmlFor=id;
    const field=add('textarea','',section);field.id=id;field.rows=4;field.maxLength=1500;field.autocomplete='off';field.spellcheck=false;field.setAttribute('aria-describedby','ip-notes-help');
   });
   status.textContent='Practice plan ready. Rebuilding or changing role clears these notes. There is no answer analysis or hiring score.';output.focus();
  });
 }
}

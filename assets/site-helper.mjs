export const TOPICS=['all','search','cv','tools','workspace','salary','safety','roles','arabic','privacy'];
const tokens=text=>text.normalize('NFKC').toLocaleLowerCase('en').match(/[\p{L}\p{N}]{2,}/gu)||[];
const STOP=new Set(['the','and','how','can','you','for','with','what','does','this','that','are','from','have','your','about']);
const topicPage=(page,topic)=>topic==='all'||({search:()=>page.path==='/'||page.path==='/jobs/'||/job-search|platforms/.test(page.path),cv:()=>/cv|^\/tools\/$/.test(page.path),tools:()=>page.path.startsWith('/tools/'),workspace:()=>page.path==='/tools/'||page.path==='/privacy-policy/',salary:()=>page.path.includes('salary'),safety:()=>/verify|scam/.test(page.path),roles:()=>/it-jobs|technical-support|customer-service|sales-jobs|finance-jobs|logistics-jobs|healthcare-jobs|hospitality-jobs/.test(page.path),arabic:()=>page.lang==='ar',privacy:()=>/privacy|terms|advertising-disclosure/.test(page.path)}[topic]?.()??false);
export function searchHelp(query='',topic='all'){
 if(typeof query!=='string'||query.length>160||!TOPICS.includes(topic))return {error:'Use a short topic or keyword, within 160 characters.'};
 const words=[...new Set(tokens(query).filter(word=>!STOP.has(word)))];
 if(query.trim()&&!words.length)return {error:'Use a specific topic such as cover letter, interview, salary, login or Arabic.'};
 const rank=(items,text)=>items.map(item=>({item,score:words.reduce((sum,word)=>sum+(tokens(text(item)).includes(word)?1:0),0)})).filter(row=>!words.length||row.score>0).sort((a,b)=>b.score-a.score).map(row=>row.item);
 return {answers:rank(ANSWERS.filter(answer=>topic==='all'||answer.topic===topic),a=>a.question+' '+a.keywords+' '+a.answer),pages:rank(CATALOGUE.filter(page=>topicPage(page,topic)),page=>page.title+' '+page.description+' '+page.path)};
}
